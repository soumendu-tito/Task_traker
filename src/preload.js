const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('tracker', {
  getState: () => ipcRenderer.invoke('state:get'),
  saveProfile: (data) => ipcRenderer.invoke('profile:save', data),
  setPreferences: (data) => ipcRenderer.invoke('preferences:set', data),
  start: () => ipcRenderer.invoke('tracking:start'),
  stop: () => ipcRenderer.invoke('tracking:stop'),
  addTask: (data) => ipcRenderer.invoke('task:add', data),
  updateTask: (id, data) => ipcRenderer.invoke('task:update', id, data),
  deleteTask: (id) => ipcRenderer.invoke('task:delete', id),
  getScreenshots: () => ipcRenderer.invoke('screenshots:list'),
  getScreenshotImage: (id) => ipcRenderer.invoke('screenshots:image', id),
  captureScreenshot: () => ipcRenderer.invoke('screenshots:capture'),
  openScreenshot: (id) => ipcRenderer.invoke('screenshots:open', id),
  exportPdf: () => ipcRenderer.invoke('report:pdf'),
  exportWeeklyPdf: () => ipcRenderer.invoke('report:pdf', 'weekly'),
  exportDailyPdf: () => ipcRenderer.invoke('report:pdf', 'daily'),
  sendEmail: (data) => ipcRenderer.invoke('email:send', data),
  telegramSave: (data) => ipcRenderer.invoke('telegram:save', data),
  telegramPair: () => ipcRenderer.invoke('telegram:pair'),
  telegramDisconnect: () => ipcRenderer.invoke('telegram:disconnect'),
  configureRelay: (data) => ipcRenderer.invoke('relay:configure', data),
  verifyRelayAdmin: (data) => ipcRenderer.invoke('relay:verify-admin', data),
  saveRelayAgentSettings: (data) => ipcRenderer.invoke('relay:save-agent-settings', data),
  pairRelayDevice: (data) => ipcRenderer.invoke('relay:pair-device', data),
  copyText: (value) => ipcRenderer.invoke('relay:copy-text', value),
  listWorkspaceMembers: () => ipcRenderer.invoke('workspace:list'),
  addWorkspaceMember: (data) => ipcRenderer.invoke('workspace:add-member', data),
  copyWorkspaceInvite: (id) => ipcRenderer.invoke('workspace:copy-invite', id),
  removeWorkspaceMember: (id) => ipcRenderer.invoke('workspace:remove-member', id),
  askAssistant: (question) => ipcRenderer.invoke('assistant:ask', question),
  onUpdate: (callback) => { ipcRenderer.on('state:update', (_event, state) => callback(state)); },
  onCapture: (callback) => { ipcRenderer.on('capture:notice', (_event, notice) => callback(notice)); },
  onTelegramNotice: (callback) => { ipcRenderer.on('telegram:notice', (_event, notice) => callback(notice)); },
});
